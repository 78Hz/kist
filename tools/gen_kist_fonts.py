#!/usr/bin/env python3
"""KIST's engraving faces for the screen: Fraktur (UnifrakturMaguntia) for the page titles, IM Fell English
(17th-century English types, roman, italic and small capitals) for everything else, rendered into fm1-base's bitmap
font format (device/gfx.c: untrimmed, 4-bit alpha) as ui/kist_fonts.h.

The faces cover ASCII; a few ASCII codes the screens never use carry the other characters they need:
    ^ -> middle dot (415^37)    { -> o-umlaut (Rohrfl{te)    } -> pilcrow (the chosen row)
    ~ -> sharp s (Fu~)          _ -> long s (Con_ole, titles only)   \\ -> plus-minus    ` -> two-thirds
Run after changing a size or a face:  python3 tools/gen_kist_fonts.py > ui/kist_fonts.h"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
PAD = 2                                    # as fm1-base's gen_font.py: the bitmap starts PAD pixels left of the pen
REMAP = {"^": "·", "{": "ö", "}": "¶", "~": "ß", "_": "ſ", "\\": "±", "`": "⅔"}
# the sizes in the old printers' scale, on the organ's own intervals: 12 the labels, 16 a fourth above (the captions
# and lists), 18 a fifth above (the values and the pipe names), 24 the octave (the titles), 36 a fifth over that
FACES = [                                  # role, file, pixel size
    ("TITLE", "UnifrakturMaguntia-Book.ttf", 24),
    ("NAME", "IMFeENrm28P.ttf", 18),           # values and the pipe names
    ("BODY", "IMFeENrm28P.ttf", 16),           # lists
    ("ITAL", "IMFeENit28P.ttf", 16),           # captions
    ("VITAL", "IMFeENit28P.ttf", 18),          # a value in italic: the chosen one, or a long one
    ("SC", "IMFeENsc28P.ttf", 12),             # labels
    ("NOTE", "IMFeENrm28P.ttf", 9),            # the note names round the Tuning page's dial
    ("BIG", "IMFeENrm28P.ttf", 36),
]
FIRST, LAST = 32, 126


def render(path, px):
    font = ImageFont.truetype(str(path), px)
    asc, desc = font.getmetrics()
    top = max(0, font.getbbox("A8|(fg")[1] - 1)
    h = asc + desc - top
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = REMAP.get(chr(c), chr(c))
        adv = int(round(font.getlength(ch)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), ch, font=font, fill=255)
        img = img.crop((0, top, bw, top + h))
        glyphs.append((adv, bw, [min(15, (v + 8) // 17) for v in img.tobytes()]))
    return h, glyphs


def main():
    out = ["/* generated by tools/gen_kist_fonts.py - do not edit. UnifrakturMaguntia and IM Fell English: SIL OFL 1.1",
           " * (assets/fonts/OFL-*.txt). Remapped: ^ middle dot, { o-umlaut, } pilcrow, ~ sharp s, _ long s, \\ plus-minus,",
           " * ` two-thirds */", "#pragma once", ""]
    total = 0
    for name, f, px in FACES:
        h, glyphs = render(FONTS / f, px)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536, name
        total += len(data)
        out.append(f"static const uint8_t KF_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const uint16_t KF_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        out.append(f"static const uint8_t KF_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        out.append(f"static const uint8_t KF_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        out.append(f"static const felucca_font_t KF_{name} = {{ {h}, {PAD}, {FIRST}, {LAST}, "
                   f"KF_{name}_ADV, KF_{name}_BW, KF_{name}_OFF, KF_{name}_DATA }};")
        out.append("")
        print(f"font {name}: {f} {px}px, height {h}, {len(data)} B", file=sys.stderr)
    print(f"fonts: {total} B in all", file=sys.stderr)
    print("\n".join(out))


if __name__ == "__main__":
    main()
