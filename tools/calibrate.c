/* KIST — the tuning calibration: how far the jet pulls each stop's pipes off their resonator pitch.
 * For each stop, across log2(f / fs), a pipe is built at f without correction, run at steady wind and measured;
 * the pull in cents goes into dsp/calib_table.h. Run it again whenever a stop's model constants change:
 *   tools/build_tools.sh && build/calibrate > dsp/calib_table.h && tools/build_tools.sh */
#include <math.h>
#include <stdio.h>
#include "organ.h"

#define LF_MIN -11.0f
#define LF_STEP 0.02f
#define LF_MAX -2.3f

static const char *NAME[NSTOPS] = {"Gedackt 8", "Rohrflote 4", "Principal 2", "Quint 2 2/3"};

int main(void)
{
    int n = (int)((LF_MAX - LF_MIN) / LF_STEP + 1.5f), s, i, bad = 0;
    static float cents[NSTOPS][500];
    for (s = 0; s < NSTOPS; s++) {
        for (i = 0; i < n; i++) {
            float lf = LF_MIN + LF_STEP * (float)i, fe = KIST_FS * exp2f(lf);
            float secs = fmaxf(0.8f, 120.0f / fe), fm = organ_probe_run(s, fe, 1.0f, 0, secs, 0, 0);
            cents[s][i] = fm > 0.0f ? 1200.0f * log2f(fm / fe) : NAN;
        }
        for (i = 0; i < n; i++)            /* a point that did not speak: from its neighbours */
            if (isnan(cents[s][i])) {
                int a = i - 1, b = i + 1;
                bad++;
                fprintf(stderr, "calibrate: %s at %.1f Hz did not speak\n", NAME[s], KIST_FS * exp2f(LF_MIN + LF_STEP * i));
                while (a >= 0 && isnan(cents[s][a]))
                    a--;
                while (b < n && isnan(cents[s][b]))
                    b++;
                cents[s][i] = a >= 0 && b < n ? 0.5f * (cents[s][a] + cents[s][b]) : a >= 0 ? cents[s][a] : b < n ? cents[s][b] : 0.0f;
            }
    }
    printf("/* Generated by tools/calibrate.c - do not edit.\n"
           " * The sounding pitch of each stop's model, in cents, relative to the resonator's nominal pitch, at\n"
           " * log2(f / fs) from CAL_LF_MIN in steps of CAL_LF_STEP. */\n#pragma once\n");
    printf("#define CAL_LF_MIN %.4ff\n#define CAL_LF_STEP %.4ff\n#define CAL_N %d\n", LF_MIN, LF_STEP, n);
    printf("static const float CAL[%d][CAL_N] = {\n", NSTOPS);
    for (s = 0; s < NSTOPS; s++) {
        printf("    /* %s */ {", NAME[s]);
        for (i = 0; i < n; i++)
            printf("%s%.2ff", i ? (i % 10 ? ", " : ",\n        ") : "", cents[s][i]);
        printf("},\n");
    }
    printf("};\n");
    fprintf(stderr, "calibrate: %d stops x %d points, %d filled in\n", NSTOPS, n, bad);
    return 0;
}
